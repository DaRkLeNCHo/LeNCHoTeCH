/**
 * Busca un texto usando una ruta como:
 *
 * language.buttonLabel
 * common.close
 *
 * @param {string} language
 * @param {string} key
 * @returns {string|null}
 */
function getTranslation(language, key) {
    const languageTranslations =
        LeNCHoTeCHTranslations[language];

    if (!languageTranslations) {
        return null;
    }

    const value =
        key
            .split(".")
            .reduce(
                (currentValue, keyPart) =>
                    currentValue?.[keyPart],
                languageTranslations
            );

    return typeof value === "string"
        ? value
        : null;
}


/**
 * Traduce los textos normales que usan data-i18n.
 *
 * Ejemplo:
 * <span data-i18n="common.close">Cerrar</span>
 *
 * @param {string} language
 */
function translateTextElements(language) {
    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {
            const translationKey =
                element.dataset.i18n;

            const translatedText =
                getTranslation(
                    language,
                    translationKey
                );

            if (translatedText !== null) {
                element.textContent =
                    translatedText;
            }
        });
}


/**
 * Traduce atributos como title, aria-label
 * y placeholder.
 *
 * @param {string} language
 */
function translateAttributeElements(language) {
    const translatedAttributes = [
        {
            selector: "[data-i18n-title]",
            datasetKey: "i18nTitle",
            attributeName: "title"
        },

        {
            selector: "[data-i18n-aria-label]",
            datasetKey: "i18nAriaLabel",
            attributeName: "aria-label"
        },

        {
            selector: "[data-i18n-placeholder]",
            datasetKey: "i18nPlaceholder",
            attributeName: "placeholder"
        }
    ];

    translatedAttributes.forEach(
        attributeConfiguration => {
            document
                .querySelectorAll(
                    attributeConfiguration
                        .selector
                )
                .forEach(element => {
                    const translationKey =
                        element.dataset[
                            attributeConfiguration
                                .datasetKey
                        ];

                    const translatedText =
                        getTranslation(
                            language,
                            translationKey
                        );

                    if (translatedText !== null) {
                        element.setAttribute(
                            attributeConfiguration
                                .attributeName,
                            translatedText
                        );
                    }
                });
        }
    );
}

/**
 * Traduce metadatos y atributos especiales
 * que no utilizan data-i18n estándar.
 *
 * @param {"es"|"en"} language
 */
function translateDocumentMetadata(language) {
    const pageTitle =
        getTranslation(
            language,
            "page.title"
        );

    if (pageTitle !== null) {
        document.title =
            pageTitle;
    }

    const descriptionMeta =
        document.querySelector(
            'meta[name="description"]'
        );

    const pageDescription =
        getTranslation(
            language,
            "page.description"
        );

    if (
        descriptionMeta &&
        pageDescription !== null
    ) {
        descriptionMeta.setAttribute(
            "content",
            pageDescription
        );
    }

    const siteLogo =
        document.getElementById(
            "site-logo"
        );

    const logoAlternative =
        getTranslation(
            language,
            "header.logoAlt"
        );

    if (
        siteLogo &&
        logoAlternative !== null
    ) {
        siteLogo.setAttribute(
            "alt",
            logoAlternative
        );
    }
}

/**
 * Aplica todas las traducciones disponibles.
 *
 * @param {"es"|"en"} language
 */
function applyTranslations(language) {
    const validLanguage =
        language === "en"
            ? "en"
            : "es";

    document.documentElement.lang =
        validLanguage;

    translateTextElements(validLanguage);
    translateAttributeElements(validLanguage);
    translateDocumentMetadata(validLanguage);


    document.dispatchEvent(
        new CustomEvent(
            "lenchotech:translations-applied",
            {
                detail: {
                    language:
                        validLanguage
                }
            }
        )
    );
}


